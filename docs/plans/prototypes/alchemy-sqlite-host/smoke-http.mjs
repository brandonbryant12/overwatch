import * as Domain from "@alchemy.run/domain";
import * as Effect from "effect/Effect";
import * as Layer from "effect/Layer";
import * as Stream from "effect/Stream";
import * as FetchHttpClient from "effect/http/FetchHttpClient";
import * as HttpEffect from "effect/http/HttpEffect";
import * as http from "node:http";
import { Readable } from "node:stream";
import { BigDepositsLive } from "./model.mjs";
import { Bank2, Bank2Api, FeedLive, seen } from "./model2.mjs";
import { layerSqlite } from "./sqlite-host.mjs";
console.log("verify:", Domain.verify(Bank2).length);
const Live = Bank2.layer(Layer.mergeAll(BigDepositsLive, FeedLive)).pipe(Layer.provide(layerSqlite(process.argv[2])));
const program = Effect.gen(function* () {
  const api = yield* Bank2Api;
  const context = yield* Effect.context();
  const handler = HttpEffect.toWebHandler(api.fetch.pipe(Effect.provide(context)));
  const server = http.createServer(async (req, res) => {
    const body = req.method === "GET" || req.method === "HEAD" ? undefined : Readable.toWeb(req);
    const response = await handler(new Request(`http://localhost${req.url}`, { method: req.method, headers: req.headers, body, duplex: "half" }));
    res.writeHead(response.status, Object.fromEntries(response.headers));
    if (response.body) Readable.fromWeb(response.body).pipe(res); else res.end();
  });
  yield* Effect.promise(() => new Promise((r) => server.listen(0, r)));
  const url = `http://localhost:${server.address().port}`;
  const bank = yield* Bank2Api.client.pipe(Effect.provide(Domain.protocolHttp(url).pipe(Layer.provide(FetchHttpClient.layer))));
  const watched = [];
  yield* Effect.forkScoped(bank.Summary.watch("b-1").pipe(Stream.runForEach((s) => Effect.sync(() => watched.push(JSON.stringify(s))))));
  yield* Effect.sleep("300 millis");
  const r1 = yield* bank.DepositMoney("b-1", { amount: 900 });
  const r2 = yield* bank.DepositMoney("b-2", { amount: 5 });
  console.log("over HTTP receipt:", JSON.stringify(r1));
  console.log("over HTTP get:", JSON.stringify(yield* bank.Summary.get("b-1", { atLeast: r1 })));
  yield* Effect.sleep("2500 millis");
  console.log("watch (HTTP stream) saw:", watched.join(" | "));
  console.log("constant-key projection saw:", seen.join(", "));
  server.closeAllConnections(); server.close();
}).pipe(Effect.scoped, Effect.provide(Live));
await Effect.runPromise(program).catch((e) => { console.error("ERR", e); process.exitCode = 1; });
process.exit();
